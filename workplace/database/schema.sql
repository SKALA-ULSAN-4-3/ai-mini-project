-- 로컬 PostgreSQL과 Aiven PostgreSQL에 공통으로 적용하는 애플리케이션
-- 스키마입니다. 관리형 DB에서는 CREATE DATABASE 권한이 제한될 수 있으므로
-- 접속 대상 데이터베이스는 배포 환경에서 먼저 선택하고 여기서는 테이블만 만듭니다.

-- 사업자 회원의 인증 정보와 필수 법인 정보를 저장합니다.
-- 비밀번호 열에는 평문이 아닌 BCrypt 해시만 저장합니다.
CREATE TABLE IF NOT EXISTS users (
    business_registration_number CHAR(10) NOT NULL,
    password VARCHAR(255) NOT NULL,
    corporate_name VARCHAR(200) NOT NULL,
    head_office_address VARCHAR(500) NOT NULL,
    business_type VARCHAR(100) NOT NULL,
    business_item VARCHAR(200) NOT NULL,
    unit_taxpayer_applicable CHAR(1) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (business_registration_number),

    CONSTRAINT chk_users_business_registration_number
        CHECK (business_registration_number ~ '^[0-9]{10}$'),

    CONSTRAINT chk_users_unit_taxpayer_applicable
        CHECK (unit_taxpayer_applicable IN ('여', '부'))
);

-- JWT의 sub에 저장되는 사업자등록번호를 기준으로 사용자 한 명당 회사 프로필
-- 하나를 저장합니다. 배열과 실적 목록은 검색과 확장이 쉬운 JSONB로 보관합니다.
-- 목록 열(licenses, certs, track_records, owned_docs, keywords)은 NULL을 "아직 안 적음
-- (모름)", 빈 배열 []을 "없음 확인"으로 구분하므로 NULL을 허용합니다.
CREATE TABLE IF NOT EXISTS company_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    business_registration_number CHAR(10) NOT NULL,

    industry VARCHAR(200) NOT NULL,
    licenses JSONB,
    region VARCHAR(100) NOT NULL,
    company_size VARCHAR(50) NOT NULL,
    certs JSONB,
    credit_rating VARCHAR(50),
    track_records JSONB,
    owned_docs JSONB,
    budget_min BIGINT,
    budget_max BIGINT,
    keywords JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),
    UNIQUE (business_registration_number),

    CONSTRAINT fk_company_profiles_user
        FOREIGN KEY (business_registration_number)
        REFERENCES users (business_registration_number)
        ON DELETE CASCADE,

    -- 음수 예산이 저장되지 않도록 자료형 대신 명시적인 CHECK로 제한합니다.
    CONSTRAINT chk_company_profiles_budget_non_negative
        CHECK (
            (budget_min IS NULL OR budget_min >= 0)
            AND (budget_max IS NULL OR budget_max >= 0)
        ),

    CONSTRAINT chk_company_profiles_budget_range
        CHECK (
            budget_min IS NULL
            OR budget_max IS NULL
            OR budget_min <= budget_max
        )
);

-- 이미 만들어진 테이블에서는 목록 열의 NOT NULL을 풉니다(이미 풀려 있으면 아무 일도 없음).
ALTER TABLE company_profiles ALTER COLUMN licenses DROP NOT NULL;
ALTER TABLE company_profiles ALTER COLUMN certs DROP NOT NULL;
ALTER TABLE company_profiles ALTER COLUMN track_records DROP NOT NULL;
ALTER TABLE company_profiles ALTER COLUMN owned_docs DROP NOT NULL;
ALTER TABLE company_profiles ALTER COLUMN keywords DROP NOT NULL;

-- region은 시·도 정식 명칭 17개 중 하나만 저장합니다(공고 로직의 지역 표기와 같음).
-- 이미 만들어진 테이블에도 적용되도록 따로 추가합니다.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_company_profiles_region'
    ) THEN
        ALTER TABLE company_profiles
            ADD CONSTRAINT chk_company_profiles_region
            CHECK (region IN (
                '서울특별시','부산광역시','대구광역시','인천광역시','광주광역시','대전광역시','울산광역시','세종특별자치시','경기도','강원특별자치도','충청북도','충청남도','전북특별자치도','전라남도','경상북도','경상남도','제주특별자치도'
            ));
    END IF;
END $$;

-- 로그인한 사업자별 공고 요약 결과입니다. business_registration_number는 JWT에서
-- 서버가 채우고, (bid_no, revision)이 정정공고 차수까지 구분합니다. 요약 JSON은 항목이
-- 바뀌어도 스키마를 고치지 않도록 JSONB로 통째로 보관합니다.
CREATE TABLE IF NOT EXISTS bid_summaries (
    business_registration_number CHAR(10) NOT NULL,
    bid_no VARCHAR(100) NOT NULL,
    revision VARCHAR(20) NOT NULL DEFAULT '000',
    summary JSONB NOT NULL,
    missing JSONB NOT NULL DEFAULT '[]'::jsonb,
    needs_review BOOLEAN NOT NULL DEFAULT FALSE,
    handoff BOOLEAN NOT NULL DEFAULT FALSE,
    latency_ms BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (business_registration_number, bid_no, revision),

    CONSTRAINT fk_bid_summaries_user
        FOREIGN KEY (business_registration_number)
        REFERENCES users (business_registration_number)
        ON DELETE CASCADE
);

-- 공고 원본 PDF의 메타데이터입니다. 파일 자체는 Supabase Storage에 있고, DB에는
-- 위치(storage_key)와 출처만 저장합니다. 다운로드 주소는 조회할 때 임시로 발급합니다.
CREATE TABLE IF NOT EXISTS bid_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    bid_no VARCHAR(100) NOT NULL,
    revision VARCHAR(20) NOT NULL DEFAULT '000',
    file_name VARCHAR(500) NOT NULL,
    storage_key VARCHAR(600) NOT NULL,
    size_bytes BIGINT NOT NULL,
    source_url TEXT,
    collected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),
    UNIQUE (storage_key),
    UNIQUE (bid_no, revision, file_name),

    CONSTRAINT chk_bid_documents_size_non_negative CHECK (size_bytes >= 0)
);

CREATE INDEX IF NOT EXISTS idx_bid_documents_bid
    ON bid_documents (bid_no, revision);

-- 선택·승인 저장: 사업자등록번호 외래키, 공고·차수별 유일성 보장.
CREATE TABLE IF NOT EXISTS user_bid_pipeline (
    business_registration_number CHAR(10) NOT NULL,
    bid_no VARCHAR(100) NOT NULL,
    revision VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'selected',
    selected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (business_registration_number, bid_no, revision),
    CONSTRAINT fk_user_bid_pipeline_user FOREIGN KEY (business_registration_number)
        REFERENCES users (business_registration_number) ON DELETE CASCADE,
    CONSTRAINT chk_user_bid_pipeline_status CHECK (
        (status = 'selected' AND approved_at IS NULL)
        OR (status = 'approved' AND approved_at IS NOT NULL)
    ),
    CONSTRAINT chk_user_bid_pipeline_bid_no CHECK (bid_no ~ '^[A-Za-z0-9_-]{1,100}$'),
    CONSTRAINT chk_user_bid_pipeline_revision CHECK (revision ~ '^[A-Za-z0-9_-]{1,20}$')
);

-- 회사별 공고 검색 결과 캐시입니다. 같은 기간·검색어라도 회사 프로필이 바뀌면
-- 추천 결과가 달라질 수 있으므로 request_hash에는 정규화한 기간·검색어·조회 한도와
-- 회사 프로필 지문을 모두 포함합니다. 결과 구조가 확장되어도 테이블 변경이 필요하지
-- 않도록 프론트에 보여 줄 최종 응답을 JSONB로 저장합니다.
CREATE TABLE IF NOT EXISTS bid_search_cache (
    business_registration_number CHAR(10) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    search_start_date DATE NOT NULL,
    search_end_date DATE NOT NULL,
    keywords JSONB NOT NULL,
    result_limit SMALLINT NOT NULL,
    profile_fingerprint CHAR(64) NOT NULL,
    result JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL
        DEFAULT (CURRENT_TIMESTAMP + INTERVAL '24 hours'),

    PRIMARY KEY (business_registration_number, request_hash),

    CONSTRAINT fk_bid_search_cache_user
        FOREIGN KEY (business_registration_number)
        REFERENCES users (business_registration_number)
        ON DELETE CASCADE,

    CONSTRAINT chk_bid_search_cache_request_hash
        CHECK (request_hash ~ '^[0-9a-f]{64}$'),

    CONSTRAINT chk_bid_search_cache_profile_fingerprint
        CHECK (profile_fingerprint ~ '^[0-9a-f]{64}$'),

    CONSTRAINT chk_bid_search_cache_period
        CHECK (search_start_date <= search_end_date),

    CONSTRAINT chk_bid_search_cache_keywords
        CHECK (jsonb_typeof(keywords) = 'array'),

    CONSTRAINT chk_bid_search_cache_result_limit
        CHECK (result_limit BETWEEN 1 AND 100),

    CONSTRAINT chk_bid_search_cache_result
        CHECK (jsonb_typeof(result) IN ('object', 'array')),

    CONSTRAINT chk_bid_search_cache_expiration
        CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_bid_search_cache_expiration
    ON bid_search_cache (expires_at);

-- 제안요청서 다운로드·변환 결과는 회사에 따라 달라지지 않으므로 모든 회사가
-- 공고번호와 정정공고 차수를 기준으로 공유합니다. PDF/HWP 원본을 DB에 넣지 않고
-- 외부 Storage 위치, 파일명, 처리 상태처럼 화면과 후속 작업에 필요한 결과만 JSONB로
-- 저장합니다. 정정공고가 나오면 revision이 달라져 이전 문서와 섞이지 않습니다.
CREATE TABLE IF NOT EXISTS bid_rfp_cache (
    bid_no VARCHAR(100) NOT NULL,
    revision VARCHAR(20) NOT NULL DEFAULT '000',
    result JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL
        DEFAULT (CURRENT_TIMESTAMP + INTERVAL '24 hours'),

    PRIMARY KEY (bid_no, revision),

    CONSTRAINT chk_bid_rfp_cache_bid_no
        CHECK (bid_no ~ '^[A-Za-z0-9_-]{1,100}$'),

    CONSTRAINT chk_bid_rfp_cache_revision
        CHECK (revision ~ '^[A-Za-z0-9_-]{1,20}$'),

    CONSTRAINT chk_bid_rfp_cache_result
        CHECK (jsonb_typeof(result) IN ('object', 'array')),

    CONSTRAINT chk_bid_rfp_cache_expiration
        CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_bid_rfp_cache_expiration
    ON bid_rfp_cache (expires_at);

-- PostgreSQL은 행 단위 TTL을 자동 실행하지 않습니다. 애플리케이션 시작 시와 캐시
-- 저장 시 이 함수를 호출하면 만료된 두 캐시를 한 번에 정리할 수 있습니다.
CREATE OR REPLACE FUNCTION purge_expired_bid_caches()
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    DELETE FROM bid_search_cache
    WHERE expires_at <= CURRENT_TIMESTAMP;

    DELETE FROM bid_rfp_cache
    WHERE expires_at <= CURRENT_TIMESTAMP;
END;
$$;
